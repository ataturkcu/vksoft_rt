#!/usr/bin/env python3
"""Embed SPIR-V binaries as C++ arrays: embed_spv.py out.h name=path.spv ..."""
import struct, sys

out = sys.argv[1]
with open(out, "w") as f:
    f.write("// Generated by tools/embed_spv.py - do not edit.\n#pragma once\n#include <cstdint>\n#include <cstddef>\n\n")
    for arg in sys.argv[2:]:
        name, path = arg.split("=", 1)
        data = open(path, "rb").read()
        assert len(data) % 4 == 0
        words = struct.unpack("<%dI" % (len(data) // 4), data)
        f.write("inline constexpr uint32_t k_%s_spv[] = {\n" % name)
        for i in range(0, len(words), 8):
            f.write("  " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",\n")
        f.write("};\n\n")
